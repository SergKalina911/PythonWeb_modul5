"""AIOHTTP — це асинхронний фреймворк, в якому реалізовано web-стек на основі asyncio
в Python. В AIOHTTP реалізовані клієнтська частина та серверна частина. Реалізація HTTP
і сам веб-сервер не використовують додаткові зовнішні бібліотеки. Вбудований веб-сервер
реалізований на рівні, достатньому для використання в реальних навантажених проектах.

Фреймворк доступний у репозиторії пакетів pip та встановлюється:

pip install aiohttp

Цей код є прикладом використання бібліотеки aiohttp для виконання асинхронного 
HTTP-запиту до веб-сайту. Він демонструє, як створити асинхронну клієнтську сесію,
виконати GET-запит і обробити отриману відповідь. Код також враховує особливості
роботи на операційній системі Windows, встановлюючи відповідну політику циклу подій
для asyncio."""

import platform
#Ця бібліотека використовується для визначення операційної системи, на якій
# виконується код. Це може бути корисно для налаштування поведінки програми
# в залежності від ОС, наприклад, для вибору відповідного політики циклу подій
# в asyncio на Windows.

import asyncio
#Ця бібліотека використовується для написання асинхронного коду в Python. Вона
# дозволяє створювати корутини, які можуть виконуватися паралельно, не блокуючи
# основний потік виконання. Це особливо корисно для задач, які вимагають очікування,
# таких як мережеві запити або операції вводу/виводу, дозволяючи програмі залишатися
# чуйною та ефективною.

import aiohttp
#Ця бібліотека використовується для виконання асинхронних HTTP-запитів. Вона
# дозволяє ефективно працювати з веб-ресурсами, не блокуючи виконання програми
# під час очікування відповіді від сервера. Це особливо корисно для створення
# клієнтських додатків, які потребують взаємодії з веб-сервісами або API.




async def main():
    """ Ця функція є основною корутиною, яка виконує асинхронний HTTP-запит до веб-сайту.
    Вона використовує aiohttp для створення клієнтської сесії та виконання"""

    async with aiohttp.ClientSession() as session:
        # Створює асинхронну клієнтську сесію, яка використовується для виконання HTTP-запитів.
        async with session.get('https://python.org') as response:
# Виконує асинхронний GET-запит до вказаної URL-адреси (https://python.org) і отримує відповідь.
            print("Status:", response.status)
            print("Content-type:", response.headers['content-type'])
# Виводить статус відповіді та тип вмісту, отримані від сервера. Це допомагає зрозуміти,
# чи був запит успішним і який тип даних повернув сервер.
            # Якщо відповідь містить HTML-код, можна його вивести або обробити далі.
            html = await response.text()
            # Асинхронно отримує текстовий вміст відповіді, який зазвичай є HTML-кодом
            # веб-сторінки. Це дозволяє обробляти вміст без блокування виконання програми.

            print("Body:", html[:15], "...")
# Виводить перші 15 символів тіла відповіді, щоб показати частину отриманого HTML-коду. Це
# допомагає підтвердити, що запит був успішним і що отримано правильний вміст, не виводячи
# весь HTML-код, який може бути дуже великим. Замість цього, виводиться лише початок, щоб
# дати уявлення про отримані дані. Це також демонструє, як можна обробляти великі відповіді
# ефективно, не перевантажуючи консоль.

if __name__ == "__main__":
    if platform.system() == 'Windows':
        # Перевіряє, чи виконується код на операційній системі Windows. Якщо так, то встановлює
        # політику циклу подій для asyncio на Windows, щоб уникнути проблем з сумісністю.
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())

    # Запускає основну корутину main() за допомогою asyncio.run(), що дозволяє виконувати
    # асинхронний код. Це забезпечує правильне управління циклом подій і дозволяє корутинам
    # виконуватися ефективно.
    asyncio.run(main())
